const { test, expect } = require('@playwright/test')
const { LoginPage } = require('../pages/LoginPage')
const { ProductsPage } = require('../pages/ProductsPage')
const { CartPage } = require('../pages/CartPage')
const {CheckOutPage  } = require('../pages/CheckoutPage')

test('verify the Jacket', async ({ page }) => {
    const loginpage = new LoginPage(page)
    const productspage = new ProductsPage(page)
    const cartpage = new CartPage(page)
    const checkoutpage = new CheckOutPage(page)
    await loginpage.navigate()
    await loginpage.enterCredentials('standard_user', 'secret_sauce')
    await loginpage.clickLoginButton()

    await productspage.verifyProductsText()
    const countProduct = await productspage.verifyProductsCount()
    console.log('Number of products : ', countProduct)
    expect(countProduct).toBe(6)
    await productspage.addJacketToCart()
    expect(await productspage.cartBadge).toHaveCount(1)
    await productspage.clickCartIcon()
    await cartpage.verifyCartTitle()
    expect(await cartpage.productTitle).toBeVisible()
    expect(await cartpage.checkoutButton).toBeVisible()
    await expect(await cartpage.jacketPrice).toHaveText('$49.99')
    await cartpage.clickCheckoutButton()
    await expect(checkoutpage.firstName).toBeVisible()
    await expect(checkoutpage.lastName).toBeVisible()
    await expect(checkoutpage.postalCode).toBeVisible()
    await checkoutpage.checkPageInputValues('Bhaskar', 'Vangapandu', '55555')
    await expect(checkoutpage.firstName).toHaveValue('Bhaskar')
    await expect(checkoutpage.lastName).toHaveValue('Vangapandu')
    await expect(checkoutpage.postalCode).toHaveValue('55555')
    await checkoutpage.clickContinueButton()
    await expect(checkoutpage.itemTotal).toHaveText('Item total: $49.99')
    await expect(checkoutpage.taxValue).toHaveText('Tax: $4.00')
    await expect(checkoutpage.total).toHaveText('Total: $53.99')
    await checkoutpage.visibleFinishButton()
    await checkoutpage.ClickFinishButton()
    await checkoutpage.verifyOrder()
    await expect(checkoutpage.Thankyou).toBeVisible()
})
test('Remove Item from the cart', async ({ page }) => {
    const loginpage = new LoginPage(page)
    const productspage = new ProductsPage(page)
    const cartpage = new CartPage(page)
    await loginpage.navigate()
    await loginpage.enterCredentials('standard_user', 'secret_sauce')
    await loginpage.clickLoginButton()
    await productspage.addJacketToCart()
    await productspage.clickCartIcon()
    await cartpage.RemoveItem()
    await expect(productspage.cartBadge).toHaveCount(0)
    await expect(cartpage.productTitle).not.toBeVisible()
    await expect(cartpage.removeButton).toHaveCount(0)

})